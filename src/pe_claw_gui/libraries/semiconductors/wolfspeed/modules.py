def _linear_value(current_a: float, rated_current_a: float, value_25: float, value_150: float, tj_c: float) -> float:
    temp_ratio = min(max((tj_c - 25.0) / 125.0, 0.0), 1.0)
    value = value_25 + temp_ratio * (value_150 - value_25)
    return value * max(abs(current_a), 0.0) / max(rated_current_a, 1e-6)


def _validate_manifest() -> None:
    seen: set[str] = set()
    duplicates: list[str] = []
    for record in WOLFSPEED_MODULE_STATIC_MANIFEST:
        validate_sic_module_static_record(record)
        if record.part_number in seen:
            duplicates.append(record.part_number)
        seen.add(record.part_number)
        for filename in (record.mosfet_xml_filename, record.sbd_xml_filename):
            if not resolve_wolfspeed_module_data_path(record, filename).exists():
                raise FileNotFoundError(f"{record.part_number}: XML resource missing: {filename}")
    if duplicates:
        raise ValueError("Duplicate Wolfspeed module seed parts: " + ", ".join(sorted(duplicates)))


