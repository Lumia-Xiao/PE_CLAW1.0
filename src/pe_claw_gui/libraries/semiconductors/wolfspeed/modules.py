@dataclass(frozen=True)
class WolfspeedSiCModule:
    """Runtime model for one Wolfspeed SiC module and module-bound diode section."""

    static: SiCModuleStaticRecord
    mosfet_loss_model: PlecsSiCSemiconductorLossModel
    diode_loss_model: PlecsSiCSemiconductorLossModel | None = None

    @property
    def has_separate_diode_xml(self) -> bool:
        return self.diode_loss_model is not None and self.static.sbd_xml_filename != self.static.mosfet_xml_filename

    @property
    def diode_section_kind(self) -> str:
        filename = self.static.sbd_xml_filename.casefold()
        if "bodydiode" in filename:
            return "body_diode"
        if "schottky" in filename or "schottkydiode" in filename:
            return "sic_sbd"
        return "module_diode"

    def eon_mJ(self, id_A: float, vds_V: float, tj_C: float, rg_on_Ohm: float) -> float:
        if self.mosfet_loss_model.turn_on is None:
            return 0.0
        return 1000.0 * self.mosfet_loss_model.turn_on.energy_J(
            id_A,
            vds_V,
            tj_C,
            variables={"Rgon": rg_on_Ohm, "Rg_on": rg_on_Ohm, "RgOn": rg_on_Ohm, "RGOn": rg_on_Ohm, "Rg": rg_on_Ohm},
            custom_tables_3d=self.mosfet_loss_model.custom_tables_3d,
            custom_tables_2d=self.mosfet_loss_model.custom_tables_2d,
            custom_tables_4d=self.mosfet_loss_model.custom_tables_4d,
            custom_tables_1d=self.mosfet_loss_model.custom_tables_1d,
        )

    def eoff_mJ(self, id_A: float, vds_V: float, tj_C: float, rg_off_Ohm: float) -> float:
        if self.mosfet_loss_model.turn_off is None:
            return 0.0
        return 1000.0 * self.mosfet_loss_model.turn_off.energy_J(
            id_A,
            vds_V,
            tj_C,
            variables={"Rgoff": rg_off_Ohm, "Rg_off": rg_off_Ohm, "RgOff": rg_off_Ohm, "RGOff": rg_off_Ohm, "Rg": rg_off_Ohm},
            custom_tables_3d=self.mosfet_loss_model.custom_tables_3d,
            custom_tables_2d=self.mosfet_loss_model.custom_tables_2d,
            custom_tables_4d=self.mosfet_loss_model.custom_tables_4d,
            custom_tables_1d=self.mosfet_loss_model.custom_tables_1d,
        )

    def vds_on_V(self, id_A: float, tj_C: float) -> float:
        if self.mosfet_loss_model.conduction is None:
            return _linear_value(id_A, self.static.id_cont_A, self.static.vds_on_typ_25C_V, self.static.vds_on_typ_150C_V, tj_C)
        return abs(self.mosfet_loss_model.conduction.lookup(max(0.0, float(id_A)), tj_C))

    def diode_vf_V(self, is_A: float, tj_C: float) -> float:
        if self.diode_loss_model is None or self.diode_loss_model.conduction is None:
            return _linear_value(is_A, self.static.is_cont_A, self.static.sbd_vf_typ_25C_V, self.static.sbd_vf_typ_150C_V, tj_C)
        return abs(self.diode_loss_model.conduction.lookup(max(0.0, float(is_A)), tj_C))

    def err_mJ(self, is_A: float, vds_V: float, tj_C: float, rg_on_Ohm: float) -> float:
        if self.diode_loss_model is None or self.diode_loss_model.turn_off is None:
            return 0.0
        return 1000.0 * self.diode_loss_model.turn_off.energy_J(
            is_A,
            vds_V,
            tj_C,
            variables={"Rgon": rg_on_Ohm, "Rg_on": rg_on_Ohm, "Rg": rg_on_Ohm},
            custom_tables_3d=self.diode_loss_model.custom_tables_3d,
            custom_tables_2d=self.diode_loss_model.custom_tables_2d,
            custom_tables_4d=self.diode_loss_model.custom_tables_4d,
            custom_tables_1d=self.diode_loss_model.custom_tables_1d,
        )

    def diode_reverse_recovery_loss_W(self, fsw_Hz: float, is_A: float, vds_V: float, tj_C: float, rg_on_Ohm: float) -> float:
        return fsw_Hz * self.err_mJ(is_A, vds_V, tj_C, rg_on_Ohm) / 1000.0

    def estimate_junction_temperature_C(self, losses: Mapping[str, float], case_temp_C: float) -> dict[str, float]:
        p_mosfet = float(losses.get("p_mosfet_W", losses.get("p_mosfet_cond_W", 0.0) + losses.get("p_mosfet_sw_W", 0.0)))
        p_diode = float(losses.get("p_diode_W", losses.get("p_diode_cond_W", 0.0) + losses.get("p_diode_rr_W", 0.0)))
        return {
            "tj_mosfet_C": case_temp_C + p_mosfet * self.static.rth_jc_mosfet_K_per_W,
            "tj_diode_C": case_temp_C + p_diode * self.static.rth_jc_sbd_K_per_W,
            "delta_t_mosfet_K": p_mosfet * self.static.rth_jc_mosfet_K_per_W,
            "delta_t_diode_K": p_diode * self.static.rth_jc_sbd_K_per_W,
        }

    def build_geometry_proxy(self) -> dict[str, Any]:
        return {
            "shape": "box_with_power_terminals",
            "label": self.static.part_number,
            "vendor": self.static.vendor,
            "device_type": self.static.device_type,
            "body": {
                "length_mm": self.static.module_length_mm,
                "width_mm": self.static.module_width_mm,
                "height_mm": self.static.module_height_mm,
                "material": "Wolfspeed SiC module simplified envelope",
                "mass_g": self.static.mass_g,
            },
        }


def normalize_wolfspeed_module_part_number(filename_or_part: str) -> str:
    stem = Path(filename_or_part).stem.upper()
    stem = re.sub(r"_(BODYDIODE|SCHOTTKYDIODE|DIODE)$", "", stem)
    stem = re.sub(r"_DATASHEET$", "", stem)
    return stem


def resolve_wolfspeed_module_data_path(record: SiCModuleStaticRecord, filename: str) -> Path:
    try:
        return Path(str(resources.files(_DEVICE_PACKAGE).joinpath(WOLFSPEED_MODULE_XML_SUBDIR, filename)))
    except Exception:
        return Path(__file__).resolve().parent / WOLFSPEED_MODULE_XML_SUBDIR / filename


def build_wolfspeed_module_static_record(part_number: str) -> SiCModuleStaticRecord:
    normalized = normalize_wolfspeed_module_part_number(part_number)
    for record in WOLFSPEED_MODULE_STATIC_MANIFEST:
        if record.part_number == normalized:
            return record
    raise KeyError(f"Wolfspeed module seed not found: {part_number}")


def build_wolfspeed_module(part_number: str) -> WolfspeedSiCModule:
    record = build_wolfspeed_module_static_record(part_number)
    validate_sic_module_static_record(record)
    switch_xml = resolve_wolfspeed_module_data_path(record, record.mosfet_xml_filename)
    diode_xml = resolve_wolfspeed_module_data_path(record, record.sbd_xml_filename)
    if not switch_xml.exists():
        raise FileNotFoundError(f"{record.part_number}: module switch XML missing: {switch_xml}")
    if not diode_xml.exists():
        raise FileNotFoundError(f"{record.part_number}: module diode XML missing: {diode_xml}")
    switch_model = PlecsSiCSemiconductorLossModel.from_xml(switch_xml)
    diode_model = PlecsSiCSemiconductorLossModel.from_xml(diode_xml)
    return WolfspeedSiCModule(record, switch_model, diode_model)


@lru_cache(maxsize=1)
def build_wolfspeed_modules() -> list[WolfspeedSiCModule]:
    _validate_manifest()
    return [build_wolfspeed_module(record.part_number) for record in WOLFSPEED_MODULE_STATIC_MANIFEST]


def build_wolfspeed_module_devices() -> list[PowerDevice]:
    return [_build_runtime_device(module) for module in build_wolfspeed_modules()]


