def list_mdc_capacitors():
    """Return validated MDC records."""

    _validate_mdc_capacitors(MDC_CAPACITORS)
    return MDC_CAPACITORS


def _validate_mdc_capacitors(candidates):
    part_numbers = set()
    for candidate in candidates:
        if candidate.part_number in part_numbers:
            raise ValueError(f"Duplicate MDC part number: {candidate.part_number}")
        part_numbers.add(candidate.part_number)
        if candidate.capacitance_f <= 0.0 or candidate.voltage_rating_dc_v <= 0.0:
            raise ValueError(f"MDC {candidate.part_number} has invalid electrical rating.")
        if not candidate.body_width_mm or not candidate.body_depth_mm or not candidate.body_height_mm:
            raise ValueError(f"MDC {candidate.part_number} has missing dimensions.")
        if candidate.rs_ohm <= 0.0:
            raise ValueError(f"MDC {candidate.part_number} has invalid ESR.")
        if candidate.terminal_count <= 0:
            raise ValueError(f"MDC {candidate.part_number} has invalid terminal count.")


