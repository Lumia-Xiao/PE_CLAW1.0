def _lead_spacing_mm(subtype: str) -> float:
    if subtype == "B32714H":
        return 27.5
    if subtype == "B32716H":
        return 37.5
    if subtype == "B32718H":
        return 52.5
    raise ValueError(f"Unsupported B32714H ... B32718H subtype: {subtype}")


def _terminal_count(subtype: str, secondary_spacing_mm: float | None) -> int:
    if subtype == "B32714H":
        return 2
    if subtype == "B32716H":
        return 4 if secondary_spacing_mm is not None else 2
    if subtype == "B32718H":
        return 4
    raise ValueError(f"Unsupported B32714H ... B32718H terminal geometry: {subtype}")


def _lead_diameter_mm(subtype: str, terminal_count: int) -> float:
    if subtype == "B32714H":
        return 0.8
    if subtype == "B32716H" and terminal_count == 2:
        return 1.0
    if subtype in {"B32716H", "B32718H"} and terminal_count == 4:
        return 1.2
    raise ValueError(f"Unsupported B32714H ... B32718H lead diameter: {subtype} {terminal_count}")


def _is_low_profile(subtype: str, secondary_spacing_mm: float | None, width_mm: float, height_mm: float) -> bool:
    return subtype == "B32716H" and secondary_spacing_mm is None and width_mm == 24.0 and height_mm in {15.0, 19.0}


def _tolerance_percent(part_number: str) -> float:
    if part_number.endswith("J000"):
        return 5.0
    if part_number.endswith("K000"):
        return 10.0
    return 0.0


def _heat_coefficient_mw_per_c(width_mm: float, height_mm: float, length_mm: float) -> float | None:
    return _HEAT_COEFFICIENT_MW_PER_C_BY_SIZE_MM.get((width_mm, height_mm, length_mm))


